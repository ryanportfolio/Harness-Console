// Skill sync: compares every Harness repository cloned under root with the template's main and
// opens and squash-merges one pull request per repository with the selected skill updates. The commit
// goes to a new branch, harness-sync/<template sha7>, deleted after the merge. Status comes from git tree
// hashes: a local skill folder whose tree matches some past template version was never edited,
// so replacing it with the current version loses nothing. Anything else is left alone.
// Before committing, the repository's own checks run in a temporary worktree: sync-codex-skills.mjs
// --check and test-codex-contract.mjs (a check that passed on main and fails after the change stops
// that repository; one already failing on main is reported in the pull request) and removed-skills.mjs
// (warnings only). Paused repositories (the server passes them from the settings file; direct callers
// fall back to sync-skip.json), and repositories archived on GitHub, are
// shown with the reason and never written; a GitHub lookup that fails blocks the repository too.

export const GIT_CRED = ['-c', 'credential.helper=', '-c', 'credential.helper=!gh auth git-credential'];
const PARTS = ['.claude/skills', '.agents/skills'];
// skill-sources.json holds the reviewed hash of each native skill's Claude folder; the template's
// sync-codex-skills.mjs --check fails when a native skill's folder no longer matches its hash.
const SOURCES = '.agents/skill-sources.json';
const REGISTRIES = ['.agents/skill-modes.json', SOURCES];
// Each active skill sits in exactly one status row of this table. Older copies of
// test-codex-contract.mjs fail on a skill with no row (the template's current one only warns).
const COMPATIBILITY = '.agents/CODEX-SKILL-COMPATIBILITY.md';
const CLASS_ROW = /^\|\s*(Native|Adapted|Capability-gated|Dangerous|Claude-only)\s*\|(.*)\|\s*$/;
// skill -> status, from the table's rows.
export function classifications(text) {
  const found = new Map();
  for (const line of String(text).split(/\r?\n/)) { const match = CLASS_ROW.exec(line); if (match) for (const skill of match[2].matchAll(/`([^`]+)`/g)) found.set(skill[1], match[1]); }
  return found;
}
const PR_TITLE = 'Sync skills from Harness-Firmware';
// Skills a repository keeps as they are: a sync never updates, replaces or removes a locked skill.
// The list lives in the repository, so it travels with it: {"version": 1, "locks": {"<skill>": "<reason>"}}.
export const LOCKS = '.agents/skill-locks.json';
const LOCK_SHAPE = `${LOCKS}: expected {"version": 1, "locks": {"<skill>": "<reason>"}}`;
export function parseLocks(text) {
  let data; try { data = JSON.parse(text); } catch { throw new Error(LOCK_SHAPE); }
  if (data?.version !== 1 || !data.locks || typeof data.locks !== 'object' || Array.isArray(data.locks) || Object.entries(data.locks).some(([name, why]) => !SKILL_NAME.test(name) || typeof why !== 'string')) throw new Error(LOCK_SHAPE);
  return new Map(Object.entries(data.locks));
}
// A missing file locks nothing; one that cannot be read stops the repository instead of unlocking it.
async function readLocks(git, rev) {
  // ls-tree prints nothing for a missing path and fails only when git cannot read the tree.
  const present = (await git(['ls-tree', rev, '--', LOCKS])).trim() !== '';
  return present ? parseLocks(await git(['show', `${rev}:${LOCKS}`])) : new Map();
}
